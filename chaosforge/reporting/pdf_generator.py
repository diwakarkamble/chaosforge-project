from pathlib import Path

from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate


def generate_pdf(report_file):
    """
    Generate a PDF version of a ChaosForge report.

    Parameters
    ----------
    report_file : Path
        TXT report generated by report_generator.py

    Returns
    -------
    Path
        Generated PDF file
    """

    report_file = Path(report_file)

    pdf_file = report_file.with_suffix(".pdf")

    document = SimpleDocTemplate(str(pdf_file))

    styles = getSampleStyleSheet()

    story = []

    with open(report_file, "r", encoding="utf-8") as fp:
        for line in fp:
            line = line.rstrip()

            #
            # Preserve blank lines
            #

            if not line:
                story.append(Paragraph("&nbsp;", styles["Normal"]))

                continue

            #
            # Escape HTML
            #

            line = line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

            #
            # Preserve spacing
            #

            line = line.replace(" ", "&nbsp;")

            story.append(
                Paragraph(f"<font face='Courier'>{line}</font>", styles["Normal"])
            )

    document.build(story)

    return pdf_file
